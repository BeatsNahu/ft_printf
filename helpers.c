#include "ft_printf.h"

void	h_print_space(int i)
{
	while (i > 0)
	{
		write (1, " ", 1);
		i--;
	}
}

void	h_print_str(int len, char *str)
{
	int	i;

	i = 0;
	while (i < len)
	{
		write (1, &str[i], 1);
		i++;
	}
}
